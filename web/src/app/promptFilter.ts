/**
 * 커스텀 프롬프트 입력 단계 필터 (FR-W08-03 · FR-EDGE-13 (a)).
 *
 * 2중 방어의 첫 겹입니다. 여기서 막으면 생성이 시작되지 않아 **크레딧이 차감되지
 * 않고**(UC-08 A1-a), 통과한 뒤 모델이 만든 결과는 생성 후 안전 필터가 다시 봅니다
 * (SAFETY_BLOCKED → 자동 반환, A1-b). 이 목록은 서버 필터를 대신하지 못합니다 —
 * 최종 판단은 서버 몫이고, 여기가 하는 일은 흔한 요청을 **결제 전에** 돌려보내는
 * 것입니다.
 *
 * 판정을 **좁게** 잡은 이유: "바꿔줘" 같은 동사로 잡으면 W-08 의 문장 틀 자체가
 * "…로 만들어줘"라 전부 걸립니다. 그래서 두 가지만 봅니다.
 *
 *   1. 견종/품종 지칭 — 문장 틀의 빈칸에 견종이 들어오면 그게 곧 품종 변경 요청입니다
 *      ("우리 애를 시바견으로 만들어줘").
 *   2. 털 + 색 — 색상어 **단독은 막지 않습니다**. "검은 턱시도"는 의상이라 허용이고,
 *      "털을 하얗게"는 털색 변경이라 차단입니다.
 */

const BREED_WORDS = [
  '품종',
  '견종',
  '시바',
  '푸들',
  '말티즈',
  '포메라니안',
  '포메',
  '치와와',
  '리트리버',
  '불독',
  '비숑',
  '웰시코기',
  '코기',
  '진돗개',
  '진도견',
  '닥스훈트',
  '슈나우저',
  '요크셔',
  '스피츠',
  '허스키',
  '사모예드',
  '보더콜리',
  '달마시안',
  '셰퍼드',
  '고양이',
]

const FUR_WORDS = ['털', '모색']
const COLOR_WORDS = ['하얀', '하얗', '흰', '검은', '검정', '갈색', '노란', '금색', '회색', '갈빛']

/** 차단 사유 문구. 통과면 null — 화면은 이 값으로 안내와 버튼 활성을 함께 정합니다. */
export function promptRejectionReason(prompt: string): string | null {
  const text = prompt.trim()
  if (!text) return null

  if (BREED_WORDS.some((word) => text.includes(word))) {
    return '품종을 바꾸는 요청은 만들 수 없어요. 배경 · 의상 · 분위기로 바꿔 보세요.'
  }

  const mentionsFur = FUR_WORDS.some((word) => text.includes(word))
  if (mentionsFur && COLOR_WORDS.some((word) => text.includes(word))) {
    return '털색을 바꾸는 요청은 만들 수 없어요. 배경 · 의상 · 분위기로 바꿔 보세요.'
  }

  return null
}
