/**
 * 브랜드 잠금 문구 — NUTTi 워드마크 + 「놀이터」 **한 덩어리**.
 *
 * 셋으로 흩어져 있었고, 그중 하나가 조용히 틀렸습니다. 랜딩 헤더와 데스크톱 GNB 는
 * 둘을 붙여 「누띠 놀이터」로 세웠는데 로그인 시트만 워드마크 혼자였습니다 — 그리고
 * 그 시트의 주석은 스스로 «앱바에선 옆에 「놀이터」가 붙어 한 덩어리지만, 여기서는
 * 혼자 섭니다» 라고 적어 두고 있었습니다. 알면서 갈라진 겁니다.
 *
 * **혼자 서면 안 되는 이유는 「누띠」가 쇼핑몰 이름이기 때문입니다.** 로그인 시트는
 * 하필 그 오해가 가장 비싼 자리입니다 — 쇼핑몰 회원이 자기 쇼핑몰 비밀번호를 넣고
 * 「로그인하지 못했어요」만 보게 됩니다. 두 계정이 별개라는 건 마이페이지에 「쇼핑몰
 * 연동」이 따로 있다는 사실이 증명합니다(W-12 D).
 *
 * 영문 «playground» 를 붙이는 길도 있었지만 안 씁니다. 이 제품은 자기 이름을 이미
 * 우리말로 세 곳에서 부릅니다 — `SITE_NAME`(app/RootLayout.tsx), 이 잠금 문구,
 * 「누띠 쇼핑몰 회원은 그대로예요 / 놀이터…」(WithdrawConfirm.tsx). 영어를 더하면
 * **네 번째 이름**이 생기고, 「놀이터」와 같은 것을 가리키는지 사용자가 판단해야 합니다.
 *
 * 워드마크는 쇼핑몰 헤더에 걸린 것과 같은 원본입니다(출처·라이선스는
 * public/brand/NOTICE.md). 서체로 흉내 내지 않습니다 — 커스텀 레터링이라 Ohsquare 로
 * 조판하면 다른 글자가 됩니다.
 *
 * **크기는 `text-*` 하나로 정합니다.** 마크 높이(`h-[0.875em]`)와 사이 간격
 * (`gap-[0.5em]`)이 글자 크기를 따라가므로, 부르는 쪽은 «이 자리에서 이름이 얼마나
 * 커야 하는가» 한 가지만 답하면 됩니다 — 앱바는 `text-base`(마크 14px), 시트 머리는
 * `text-2xl`(마크 21px). 두 값을 따로 적던 시절에는 한쪽만 키우면 마크와 「놀이터」의
 * 균형이 조용히 어긋났습니다.
 */

export function BrandLockup({
  className = '',
  /**
   * 장식으로 둘 때(`aria-hidden`). 옆이나 위에 같은 이름이 **글자로** 이미 있는
   * 자리에서만 씁니다 — 로그인 시트가 그렇습니다(`<h2>` 가 이름을 답니다). 둘 다
   * 읽히면 스크린리더가 브랜드 이름을 두 번 읽습니다.
   */
  decorative = false,
}: {
  className?: string
  decorative?: boolean
}) {
  return (
    <span
      aria-hidden={decorative || undefined}
      className={`flex items-center gap-[0.5em] ${className}`}
    >
      {/*
        alt 는 「누띠」 한 단어입니다. 뒤에 오는 「놀이터」와 이어져 스크린리더가
        「누띠 놀이터」로 읽습니다 — 링크 이름은 내용에서 계산되므로 이 둘이 한
        요소 안에 같이 있어야 한 덩어리로 읽힙니다.

        width/height 는 고유비(1540×396 = 3.89:1) 그대로입니다. 로고가 늦게 와도
        줄이 밀리지 않게 자리를 미리 잡습니다.
      */}
      <img
        src="/brand/nutti-wordmark.svg"
        alt={decorative ? '' : '누띠'}
        width={70}
        height={18}
        className="h-[0.875em] w-auto"
      />
      <span className="font-display">놀이터</span>
    </span>
  )
}
